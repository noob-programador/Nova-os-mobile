/**
 * Returns CSS filter string for color blind simulation
 */
export function getColorBlindFilter(mode: ColorBlindMode): string {
  switch (mode) {
    case 'protanopia':
      return 'url(#protanopia-filter)';
    case 'deuteranopia':
      return 'url(#deuteranopia-filter)';
    case 'tritanopia':
      return 'url(#tritanopia-filter)';
    case 'monochrome':
      return 'grayscale(100%)';
    case 'none':
    default:
      return 'none';
  }
}
