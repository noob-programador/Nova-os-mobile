export function getTranslation(lang: Language, section: string, key: string): string {
  const current = translations[lang] || translations['pt-BR'];
  const sect = current[section] as Record<string, string> | undefined;
  if (sect && sect[key]) {
    return sect[key];
  }
  const fallback = translations['pt-BR'][section] as Record<string, string> | undefined;
  return (fallback && fallback[key]) || key;
}
